// In-Memory Storage Cache with localStorage sync
class MockStorage {
  constructor() {
    this.conversations = this.loadConversations()
    this.messages = this.loadMessages()
  }

  loadConversations() {
    try {
      const data = localStorage.getItem(STORAGE_KEY_CONVERSATIONS)
      if (data) return JSON.parse(data)
    } catch {
      // LocalStorage not available or parse error
    }
    return [...INITIAL_CONVERSATIONS]
  }

  loadMessages() {
    try {
      const data = localStorage.getItem(STORAGE_KEY_MESSAGES)
      if (data) return JSON.parse(data)
    } catch {
      // LocalStorage not available or parse error
    }
    return { ...INITIAL_MESSAGES }
  }

  save() {
    try {
      localStorage.setItem(STORAGE_KEY_CONVERSATIONS, JSON.stringify(this.conversations))
      localStorage.setItem(STORAGE_KEY_MESSAGES, JSON.stringify(this.messages))
    } catch {
      // Ignore storage errors
    }
  }
}

const mockStore = new MockStorage()

// Helper: simulate network delay
const delay = (ms = 700) => new Promise((resolve) => setTimeout(resolve, ms))

