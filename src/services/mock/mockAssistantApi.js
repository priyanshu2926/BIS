/**
 * Mock Assistant API Service
 */
export const mockAssistantApi = {
  /**
   * Fetch all conversations
   * @returns {Promise<{ conversations: Array }>}
   */
  async getConversations() {
    await delay(350)
    return {
      conversations: [...mockStore.conversations].sort(
        (a, b) => new Date(b.updated_at).getTime() - new Date(a.updated_at).getTime()
      ),
    }
  },

  /**
   * Fetch a single conversation with its messages
   * @param {string} conversationId
   * @returns {Promise<{ conversation: Object, messages: Array }>}
   */
  async getConversation(conversationId) {
    await delay(300)
    const conversation = mockStore.conversations.find((c) => c.id === conversationId)
    if (!conversation) {
      throw new Error(`Conversation ${conversationId} not found`)
    }
    const messages = mockStore.messages[conversationId] || []
    return {
      conversation,
      messages: [...messages],
    }
  },

  /**
   * Create a new conversation
   * @param {string} [title='New Conversation']
   * @returns {Promise<{ conversation: Object }>}
   */
  async createConversation(title = 'New Conversation') {
    await delay(300)
    const newConv = createConversation({ title })
    mockStore.conversations.unshift(newConv)
    mockStore.messages[newConv.id] = []
    mockStore.save()
    return { conversation: newConv }
  },

  /**
   * Delete a conversation
   * @param {string} conversationId
   * @returns {Promise<{ success: boolean, id: string }>}
   */
  async deleteConversation(conversationId) {
    await delay(300)
    mockStore.conversations = mockStore.conversations.filter((c) => c.id !== conversationId)
    delete mockStore.messages[conversationId]
    mockStore.save()
    return { success: true, id: conversationId }
  },

  /**
   * Send a message and receive assistant answer with sources
   * @param {Object} params
   * @param {string} params.conversationId
   * @param {string} params.message
   * @returns {Promise<{ message: Object, conversation: Object }>}
   */
  async sendMessage({ conversationId, message }) {
    await delay(800) // Realistic RAG + LLM inference latency simulation

    if (!message || !message.trim()) {
      throw new Error('Message content cannot be empty.')
    }

    // Ensure conversation exists or create one
    let conversation = mockStore.conversations.find((c) => c.id === conversationId)
    if (!conversation) {
      const generatedTitle = message.length > 32 ? `${message.substring(0, 32)}...` : message
      conversation = createConversation({ id: conversationId, title: generatedTitle })
      mockStore.conversations.unshift(conversation)
      mockStore.messages[conversationId] = []
    }

    // Create user message
    const userMsg = createMessage({
      conversationId,
      role: ROLES.USER,
      content: message,
    })

    if (!mockStore.messages[conversationId]) {
      mockStore.messages[conversationId] = []
    }
    mockStore.messages[conversationId].push(userMsg)

    // Generate AI answer & sources
    const { content, sources } = generateMockResponse(message, conversationId)
    const assistantMsg = createMessage({
      conversationId,
      role: ROLES.ASSISTANT,
      content,
      sources,
    })

    mockStore.messages[conversationId].push(assistantMsg)

    // Update conversation metadata
    conversation.updated_at = new Date().toISOString()
    conversation.message_count = mockStore.messages[conversationId].length
    conversation.last_message = message.substring(0, 60)
    if (conversation.title === 'New Conversation' || conversation.title === '') {
      conversation.title = message.length > 35 ? `${message.substring(0, 35)}...` : message
    }

    mockStore.save()

    return {
      message: assistantMsg,
      conversation,
    }
  },

  /**
   * Regenerate the last assistant response or a specific message
   * @param {Object} params
   * @param {string} params.conversationId
   * @param {string} params.messageId
   * @returns {Promise<{ message: Object }>}
   */
  async regenerateMessage({ conversationId, messageId }) {
    await delay(750)
    const messages = mockStore.messages[conversationId] || []
    const targetIndex = messages.findIndex((m) => m.id === messageId)

    if (targetIndex === -1) {
      throw new Error('Message not found for regeneration.')
    }

    // Find the preceding user prompt
    let previousUserPrompt = 'BIS standards guidance'
    for (let i = targetIndex - 1; i >= 0; i--) {
      if (messages[i].role === ROLES.USER) {
        previousUserPrompt = messages[i].content
        break
      }
    }

    const { content, sources } = generateMockResponse(previousUserPrompt, conversationId)

    const updatedMessage = {
      ...messages[targetIndex],
      content: `${content}\n\n*(Regenerated response)*`,
      sources,
      created_at: new Date().toISOString(),
    }

    messages[targetIndex] = updatedMessage
    mockStore.save()

    return { message: updatedMessage }
  },

  /**
   * Clear all messages in a conversation
   * @param {string} conversationId
   * @returns {Promise<{ success: boolean }>}
   */
  async clearConversation(conversationId) {
    await delay(250)
    mockStore.messages[conversationId] = []
    const conv = mockStore.conversations.find((c) => c.id === conversationId)
    if (conv) {
      conv.message_count = 0
      conv.last_message = ''
      conv.updated_at = new Date().toISOString()
    }
    mockStore.save()
    return { success: true }
  },
}
